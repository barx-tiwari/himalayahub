const NP_DIGITS = ['०', '१', '२', '३', '४', '५', '६', '७', '८', '९'];
export const toNepaliDigits = (value) =>
  String(value).replace(/[0-9]/g, (d) => NP_DIGITS[Number(d)]);

const yearTotal = (y) => BS_DATA[y].reduce((a, b) => a + b, 0);

export function isBsYearSupported(year) {
  return Number.isInteger(year) && year >= BS_MIN_YEAR && year <= BS_MAX_YEAR;
}

export function getBsMonthDays(year, month) {
  if (!isBsYearSupported(year)) throw new RangeError(`BS year must be between ${BS_MIN_YEAR} and ${BS_MAX_YEAR}.`);
  if (month < 1 || month > 12) throw new RangeError('BS month must be between 1 and 12.');
  return BS_DATA[year][month - 1];
}

export function getAdMonthDays(year, month) {
  return new Date(Date.UTC(year, month, 0)).getUTCDate();
}

/** Supported AD range derived from the table. */
export const AD_MIN = { year: 1943, month: 4, day: 14 };
export const AD_MAX = (() => {
  let total = 0;
  for (let y = BS_MIN_YEAR; y <= BS_MAX_YEAR; y += 1) total += yearTotal(y);
  const d = new Date(ANCHOR_UTC + (total - 1) * DAY_MS);
  return { year: d.getUTCFullYear(), month: d.getUTCMonth() + 1, day: d.getUTCDate() };
})();

/** Convert an AD date (month 1-12) to BS. Returns { year, month, day, weekday }. */
export function adToBs(year, month, day) {
  const utc = Date.UTC(year, month - 1, day);
  const check = new Date(utc);
  if (check.getUTCFullYear() !== year || check.getUTCMonth() !== month - 1 || check.getUTCDate() !== day) {
    throw new RangeError('That English date does not exist.');
  }
  let remaining = Math.round((utc - ANCHOR_UTC) / DAY_MS);
  if (remaining < 0) throw new RangeError('Dates before 14 April 1943 are not supported.');

  let bsYear = BS_MIN_YEAR;
  while (bsYear <= BS_MAX_YEAR && remaining >= yearTotal(bsYear)) {
    remaining -= yearTotal(bsYear);
    bsYear += 1;
  }
  if (bsYear > BS_MAX_YEAR) {
    throw new RangeError(`Dates after ${AD_MAX.year}-${AD_MAX.month}-${AD_MAX.day} are not supported.`);
  }
  let bsMonth = 1;
  while (remaining >= BS_DATA[bsYear][bsMonth - 1]) {
    remaining -= BS_DATA[bsYear][bsMonth - 1];
    bsMonth += 1;
  }
  return { year: bsYear, month: bsMonth, day: remaining + 1, weekday: check.getUTCDay() };
}

/** Convert a BS date (month 1-12) to AD. Returns { year, month, day, weekday }. */
export function bsToAd(year, month, day) {
  const monthDays = getBsMonthDays(year, month);
  if (!Number.isInteger(day) || day < 1 || day > monthDays) {
    throw new RangeError(`${BS_MONTHS[month - 1]} ${year} has ${monthDays} days.`);
  }
  let days = 0;
  for (let y = BS_MIN_YEAR; y < year; y += 1) days += yearTotal(y);
  for (let m = 1; m < month; m += 1) days += BS_DATA[year][m - 1];
  days += day - 1;
  const d = new Date(ANCHOR_UTC + days * DAY_MS);
  return { year: d.getUTCFullYear(), month: d.getUTCMonth() + 1, day: d.getUTCDate(), weekday: d.getUTCDay() };
}

export function todayAd() {
  const now = new Date();
  return { year: now.getFullYear(), month: now.getMonth() + 1, day: now.getDate(), weekday: now.getDay() };
}

export function todayBs() {
  const t = todayAd();
  return adToBs(t.year, t.month, t.day);
}

const pad = (n) => String(n).padStart(2, '0');
export const formatIso = ({ year, month, day }) => `${year}-${pad(month)}-${pad(day)}`;
export const formatAdLong = ({ year, month, day }) => `${AD_MONTHS[month - 1]} ${day}, ${year}`;
export const formatBsLong = ({ year, month, day }) => `${BS_MONTHS[month - 1]} ${day}, ${year}`;
export const formatBsNepali = ({ year, month, day }) =>
  `${BS_MONTHS_NP[month - 1]} ${toNepaliDigits(day)}, ${toNepaliDigits(year)}`;
